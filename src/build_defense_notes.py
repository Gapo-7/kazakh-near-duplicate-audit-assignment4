from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
summary = json.loads((ROOT / "results" / "summary.json").read_text(encoding="utf-8"))
rows = summary["corpora"]
parts = [
    "# Assignment 4 individual defence notes",
    "",
    "Each student should be ready to answer all five question types. Speak from understanding; do not read this file word for word.",
    "",
    "## 1 Protocol and setup",
    "We asked how much near-duplicate text remains after exact deduplication in four public Kazakh datasets. The Assignment 3 run was a pilot. Before final data collection, we fixed three new non-overlapping block samples, seeds 20261105–20261107, a 150–5,000-word screen, MD5 exact removal, a word five-gram baseline, character seven-gram Jaccard as our main method, and threshold 0.80. The same rows and preprocessing were used for both near methods. The protocol was hashed locally before the final run. It was not uploaded to Moodle early; this is disclosed as a deviation.",
    "",
    "## 2 Main result and statistical test",
    "One sentence: the character method still found additional near-duplicate flags after exact removal, but the rate differed sharply by dataset and random block sample.",
    "",
    "| Corpus | Three character counts | Mean ± SD | Word mean ± SD | Difference in percentage points | Exact p / Holm p |",
    "|---|---|---|---|---:|---:|",
]
for row in rows:
    counts = ", ".join(f"{r['character_flags']}/{r['post_exact']}" for r in row["per_run"])
    parts.append(f"| {row['source_label']} | {counts} | {100*row['character_mean_rate']:.2f}% ± {100*row['character_sd_rate']:.2f}% | {100*row['word_mean_rate']:.2f}% ± {100*row['word_sd_rate']:.2f}% | {row['difference_percentage_points']:+.3f} | {row['exact_sign_flip_p']:.3f} / {row['holm_adjusted_p']:.3f} |")
parts += [
    "",
    "The statistical comparison uses the difference between character and word flag rates in each of the three paired runs. We enumerate the eight possible sign flips, then apply Holm correction across four corpora. With only three runs, p-values are coarse, so this is exploratory. The percentage-point difference shows practical size. The exact-only baseline has zero near flags by definition and is not suitable for a significance test against the near methods.",
    "",
    "## 3 Errors and sensitivity",
    "An automatic flag is a candidate, not guaranteed true redundancy. Appendix B lists 73 AI-assisted draft case labels: repeated body, changed version, shared template, partial overlap, unrelated and uncertain. A bilingual student must check these against the local full texts before submission. A shared lesson-plan template can cause a false positive; a revised article below 0.80 can cause a false negative. The threshold sweep 0.75, 0.80, 0.85, 0.90 shows how many flags change when the rule becomes stricter. Keep 0.80 as the primary result because it was fixed before the final runs.",
    "",
    "## 4 Literature and limitations",
    "Tukenov (2026) describes MD5 exact deduplication in the SozKZ Kazakh corpus. Our study tests what an additional lexical step can flag in different public data. Biloshchytska et al. (2025) use a hybrid lexical and semantic approach on a benchmark, so their method can address paraphrases that our Jaccard rule may miss. Nguyen et al. (2024) use multistage cleaning in CulturaX. The main validity threat is that a Jaccard cluster can reflect shared boilerplate rather than repeated substantive content. Block sampling also misses near neighbours outside the selected rows; no sample rate is a full-dataset prevalence estimate.",
    "",
    "## 5 Pick-a-number demonstration",
    "For any row in the per-run table, open `results/run_<source_key>_<seed>.json`. Show `post_exact` for the denominator and `methods.character_7.threshold_results[\"0.8\"].flagged_records` for the numerator. The word baseline is under `methods.word_5`. The exact-removal count is under `excluded.exact_removed`. The aggregate table is regenerated by `src/summarize_results.py` from `results/final_results.json`. The validator checks all twelve runs. Be ready to run the script or open the JSON during the defence.",
    "",
    "## Important honesty points",
    "Do not claim a model was trained, that the whole datasets were measured, that every flag is a human-verified duplicate, or that the Moodle pre-run upload happened. The independent reproduction record in Appendix C must name the real person who reran the code; do not invent one.",
]
out = ROOT / "report" / "Assignment4_Individual_Defence_Notes.md"
